use std::collections::{HashMap,HashSet};
#[derive(Default)]
pub struct QuestionBuffer {
    pub parts: Vec<(String, String)>,
    seen: HashSet<String>,
    pub last_voice: i64,
    pub last_submitted: String,
    pub question_id: Option<String>,
    pub submitted_at: i64,
    pub revision: u32,
    utterance_break: bool,
    last_final_at: i64,
    pending_asr: HashMap<String,i64>,
}
pub fn is_question(text: &str) -> bool {
    let text = text.trim();
    if text.chars().count() < 4 {
        return false;
    }
    if ["好的", "嗯嗯", "谢谢", "明白了", "听得见", "你好"]
        .iter()
        .any(|s| text.trim_matches(['。', '，', '！', '?', '？', ' ']) == *s)
    {
        return false;
    }
    text.contains(['？', '?'])
        || [
            "什么",
            "怎么",
            "如何",
            "为什么",
            "是否",
            "能否",
            "能不能",
            "说说",
            "介绍",
            "解释",
            "谈谈",
            "讲讲",
            "比较",
            "区别",
            "实现",
            "设计",
            "举例",
            "如果",
            "那你",
            "那么",
        ]
        .iter()
        .any(|s| text.contains(s))
}
fn without_leading_separator(text: &str) -> &str {
    text.trim_start_matches(|c: char| {
        c.is_whitespace()
            || [
                '，', ',', '；', ';', '、', '：', ':', '？', '?', '。', '！', '!', '…',
            ]
            .contains(&c)
    })
}
fn explicit_new_question(text: &str) -> bool {
    let text = without_leading_separator(text);
    [
        "下一个问题",
        "接下来一个问题",
        "接下来问",
        "换个问题",
        "再问一个",
        "我们换个问题",
    ]
    .iter()
    .any(|s| text.starts_with(s))
}
fn continuation(text: &str) -> bool {
    let text = text.trim_start();
    if explicit_new_question(text) {
        return false;
    }
    text.starts_with(['，', ',', '；', ';', '、', '：', ':'])
        || [
            "另外",
            "如果",
            "那如果",
            "并且",
            "补充",
            "还有",
            "假设",
            "以及",
            "同时",
            "然后",
            "包括",
        ]
        .iter()
        .any(|s| text.starts_with(s))
}
impl QuestionBuffer {
    pub fn observe_voice(&mut self, at: i64) {
        if self.question_id.is_some() && at - self.last_voice > 1500 {
            self.utterance_break = true;
        }
        self.last_voice = self.last_voice.max(at);
    }
    pub fn push(&mut self, id: &str, text: &str) {
        let text = text.trim();
        self.pending_asr.remove(id);
        if let Some(part) = self.parts.iter_mut().find(|p| p.0 == id) {
            part.1 = text.into();
            self.utterance_break = false;
            return;
        }
        if self.seen.contains(id) {
            return;
        }
        let new_question = !self.last_submitted.is_empty()
            && (explicit_new_question(text)
                || (is_question(text)
                    && !continuation(text)
                    && self.utterance_break));
        if new_question {
            self.parts.clear();
            self.last_submitted.clear();
            self.question_id = None;
        }
        self.seen.insert(id.into());
        self.parts.push((id.into(), text.into()));
        self.utterance_break = false;
    }
    // ASR punctuation is generated by the provider. Only a real speech break or
    // an explicit topic change can start a new question after submission.
    pub fn push_final_at(&mut self,id:&str,text:&str,received_at:i64){
        self.push(id,text);self.last_final_at=self.last_final_at.max(received_at);
    }
    pub fn observe_partial(&mut self,id:&str,text:&str,at:i64){
        if text.trim().is_empty()||self.seen.contains(id){return;}
        self.pending_asr.retain(|_,last|at-*last<2000);
        self.pending_asr.insert(id.into(),at);
    }
    pub fn text(&self) -> String {
        let text = self
            .parts
            .iter()
            .map(|part| part.1.as_str())
            .collect::<Vec<_>>()
            .join("");
        without_leading_separator(&text).to_owned()
    }
    pub fn take(
        &mut self,
        now: i64,
        manual: bool,
        silence: u64,
    ) -> Option<(String, String, u32, i64)> {
        let text = self.text();
        if text.trim().is_empty()
            || text == self.last_submitted
            || (!manual && (!is_question(&text) || now - self.last_voice < silence as i64
                || now-self.last_final_at<350 || self.pending_asr.values().any(|at|now-*at<2000)))
        {
            return None;
        }
        let revision = self.question_id.is_some();
        let id = self
            .question_id
            .clone()
            .unwrap_or_else(crate::types::new_id);
        self.revision = if revision { self.revision + 1 } else { 1 };
        self.question_id = Some(id.clone());
        self.last_submitted = text.clone();
        self.submitted_at = now;
        Some((id, text, self.revision, self.last_voice))
    }
    pub fn expire(&mut self, now: i64) {
        self.pending_asr.retain(|_,at|now-*at<2000);
        if now - self.submitted_at > 4500
            && now - self.last_voice > 4500
            && self.pending_asr.is_empty()
            && !self.last_submitted.is_empty()
            && self.text() == self.last_submitted
        {
            self.parts.clear();
            self.last_submitted.clear();
            self.question_id = None;
            self.utterance_break = false;
        }
        if self.parts.len() > 60 {
            self.parts.drain(..self.parts.len() - 30);
        }
    }
}
#[cfg(test)]
mod tests {
    use super::*;
    #[test]
    fn questions() {
        assert!(is_question("介绍一下你的项目"));
        assert!(!is_question("好的，谢谢。"));
    }
    #[test]
    fn dedup_and_revision() {
        let mut q = QuestionBuffer {
            last_voice: 1000,
            ..Default::default()
        };
        q.push("1", "请介绍你的项目");
        assert!(q.take(1500, false, 700).is_none());
        let first = q.take(1800, false, 700).unwrap();
        assert!(q.take(1900, false, 700).is_none());
        q.push("1", "请介绍你的项目架构");
        let second = q.take(2200, false, 700).unwrap();
        assert_eq!(first.0, second.0);
        assert_eq!(second.2, 2);
    }
    #[test]
    fn short_manual() {
        let mut q = QuestionBuffer::default();
        q.push("1", "缓存");
        assert!(q.take(1000, true, 700).is_some());
    }
}

#[cfg(test)]
mod scenarios {
    use super::*;
    #[test]
    fn a_new_question_gets_its_own_id() {
        let mut buffer = QuestionBuffer {
            last_voice: 1000,
            ..Default::default()
        };
        buffer.push("a", "介绍你的项目架构？");
        let first = buffer.take(1800, false, 700).unwrap();
        buffer.observe_voice(3000);
        buffer.push("b", "如何处理缓存穿透？");
        let next = buffer.take(3800, false, 700).unwrap();
        assert_ne!(first.0, next.0);
        assert_eq!(next.1, "如何处理缓存穿透？");
        assert_eq!(next.2, 1);
    }
    #[test]
    fn a_late_condition_revises_the_same_question() {
        let mut buffer = QuestionBuffer {
            last_voice: 1000,
            ..Default::default()
        };
        buffer.push("a", "如何设计缓存？");
        let first = buffer.take(1800, false, 700).unwrap();
        buffer.last_voice = 2200;
        buffer.push("b", "如果有十万并发呢？");
        assert!(buffer.take(2400, false, 700).is_none());
        let revision = buffer.take(3000, false, 700).unwrap();
        assert_eq!(first.0, revision.0);
        assert_eq!(revision.2, 2);
        assert!(revision.1.contains("十万并发"));
    }
    #[test]
    fn confirmed_text_is_not_retriggered_after_expiration() {
        let mut buffer = QuestionBuffer {
            last_voice: 1000,
            ..Default::default()
        };
        buffer.push("a", "如何设计缓存？");
        buffer.take(1800, false, 700).unwrap();
        buffer.expire(8000);
        buffer.push("a", "如何设计缓存？");
        assert!(buffer.take(9000, false, 700).is_none());
    }
}

#[cfg(test)]
mod fragment_regressions {
    use super::*;
    fn first_part() -> (QuestionBuffer, String) {
        let mut buffer = QuestionBuffer {
            last_voice: 1000,
            ..Default::default()
        };
        buffer.push("first", "请介绍一下缓存的实现原理");
        let (id, _, _, _) = buffer.take(1800, false, 700).unwrap();
        (buffer, id)
    }
    #[test]
    fn comma_fragment_revises_the_complete_question() {
        let (mut buffer, id) = first_part();
        buffer.observe_voice(2200);
        buffer.push("second", "，如何处理缓存穿透");
        let combined = buffer.take(3000, false, 700).unwrap();
        assert_eq!(combined.0, id);
        assert_eq!(combined.1, "请介绍一下缓存的实现原理，如何处理缓存穿透");
        assert_eq!(combined.2, 2);
    }
    #[test]
    fn continuing_speech_keeps_the_first_half_beyond_the_old_timeout() {
        let (mut buffer, id) = first_part();
        buffer.observe_voice(6000);
        buffer.expire(6500);
        assert!(!buffer.text().is_empty());
        buffer.observe_voice(9300);
        buffer.push("second", "，如何处理缓存穿透");
        let combined = buffer.take(10100, false, 700).unwrap();
        assert_eq!(combined.0, id);
        assert_eq!(combined.2, 2);
        assert!(combined.1.starts_with("请介绍一下缓存"));
    }
    #[test]
    fn a_pause_separates_an_independent_question_without_asr_punctuation() {
        let (mut buffer, id) = first_part();
        buffer.observe_voice(4000);
        buffer.push("new", "请介绍垃圾回收机制");
        let next = buffer.take(4800, false, 700).unwrap();
        assert_ne!(next.0, id);
        assert_eq!(next.1, "请介绍垃圾回收机制");
    }
    #[test]
    fn consecutive_task_fragments_without_punctuation_stay_together() {
        let (mut buffer, id) = first_part();
        buffer.observe_voice(2200);
        buffer.push("second", "以及如何处理缓存穿透");
        let next = buffer.take(3000, false, 700).unwrap();
        assert_eq!(next.0, id);
        assert!(next.1.contains("实现原理以及如何"));
    }
    #[test]
    fn an_explicit_new_question_overrides_a_leading_comma() {
        let (mut buffer, id) = first_part();
        buffer.observe_voice(2200);
        buffer.push("new", "，下一个问题，介绍垃圾回收机制");
        let next = buffer.take(3000, false, 700).unwrap();
        assert_ne!(next.0, id);
        assert_eq!(next.1, "下一个问题，介绍垃圾回收机制");
    }
    #[test]
    fn an_orphan_fragment_does_not_display_a_leading_comma() {
        let mut buffer = QuestionBuffer::default();
        buffer.push("orphan", " ，如何处理缓存穿透");
        assert_eq!(buffer.text(), "如何处理缓存穿透");
    }
    #[test]
    fn leading_asr_punctuation_is_removed_from_the_complete_question() {
        let mut buffer = QuestionBuffer::default();
        buffer.push("first", "？请介绍一下缓存的实现原理");
        buffer.push("second", "，如何处理缓存穿透？");
        let question = buffer.take(1000, false, 700).unwrap();
        assert_eq!(question.1, "请介绍一下缓存的实现原理，如何处理缓存穿透？");
        assert_eq!(
            without_leading_separator(".NET 的缓存如何实现？"),
            ".NET 的缓存如何实现？"
        );
    }
    #[test]
    fn punctuation_only_segments_are_empty_until_words_arrive() {
        let mut buffer = QuestionBuffer::default();
        buffer.push("punctuation", " ？ ?。！… ");
        assert!(buffer.take(1000, true, 700).is_none());
        buffer.push("words", "如何处理缓存穿透？");
        assert_eq!(
            buffer.take(1000, false, 700).unwrap().1,
            "如何处理缓存穿透？"
        );
    }
    #[test]
    fn an_asr_revision_cannot_restore_leading_punctuation() {
        let mut buffer = QuestionBuffer::default();
        buffer.push("first", "请介绍缓存");
        let first = buffer.take(1000, false, 700).unwrap();
        buffer.push("first", "？请介绍缓存原理？");
        let revised = buffer.take(2000, false, 700).unwrap();
        assert_eq!(first.0, revised.0);
        assert_eq!(revised.1, "请介绍缓存原理？");
        assert_eq!(revised.2, 2);
    }
}

#[cfg(test)]
mod repeated_questions {
    use super::*;
    #[test]
    fn each_repeated_two_part_question_retains_its_own_first_half() {
        let mut buffer = QuestionBuffer::default();
        let mut ids = HashSet::new();
        for turn in 0..3 {
            let start = 1000 + turn * 15000;
            buffer.expire(start);
            buffer.observe_voice(start);
            buffer.push(&format!("{turn}-first"), "介绍缓存的实现原理");
            let first = buffer.take(start + 800, false, 700).unwrap();
            assert!(ids.insert(first.0.clone()));
            buffer.observe_voice(start + 2400);
            buffer.push(&format!("{turn}-second"), "，如何处理缓存穿透");
            let full = buffer.take(start + 3200, false, 700).unwrap();
            assert_eq!(first.0, full.0);
            assert_eq!(full.1, "介绍缓存的实现原理，如何处理缓存穿透");
            assert_eq!(full.2, 2);
        }
    }
}

