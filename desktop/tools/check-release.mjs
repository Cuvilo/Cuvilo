import assert from 'node:assert/strict';
import { readFileSync } from 'node:fs';
const json = path => JSON.parse(readFileSync(new URL(path, import.meta.url), 'utf8').replace(/^\uFEFF/, ''));
const config = json('../src-tauri/tauri.conf.json');
const pkg = json('../package.json');
const lock = json('../package-lock.json');
const cargo = readFileSync(new URL('../src-tauri/Cargo.toml', import.meta.url), 'utf8');
const nativeVersion = cargo.match(/\[package\][\s\S]*?\nversion\s*=\s*"([^"]+)"/)[1];
assert.match(config.version, /^\d+\.\d+\.\d+$/, 'Stable releases require x.y.z');
assert.equal(pkg.version, config.version);
assert.equal(lock.version, config.version);
assert.equal(lock.packages[''].version, config.version);
assert.equal(nativeVersion, config.version);
const cargoLock = readFileSync(new URL('../src-tauri/Cargo.lock', import.meta.url), 'utf8');
assert.equal(cargoLock.match(/name = "cuvilo"\r?\nversion = "([^"]+)"/)[1], config.version);
assert.equal(config.identifier, 'local.interview.copilot');
assert.equal(config.bundle.createUpdaterArtifacts, true);
assert.equal(config.plugins.updater.endpoints[0], 'https://github.com/Cuvilo/Cuvilo/releases/latest/download/latest.json');
assert.ok(config.plugins.updater.pubkey.length > 50);
if (process.env.GITHUB_REF_TYPE === 'tag') assert.equal(process.env.GITHUB_REF_NAME, `v${config.version}`, 'Tag and app version differ');
console.log(`Release metadata validated: Cuvilo ${config.version}`);
